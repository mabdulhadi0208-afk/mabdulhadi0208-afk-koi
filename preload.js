const {contextBridge,ipcRenderer}=require('electron');
const sub=(ch,cb)=>ipcRenderer.on(ch,(_e,d)=>cb(d));
contextBridge.exposeInMainWorld('koiAPI',{
  onShow:cb=>sub('koi:show',cb),
  onApps:cb=>sub('koi:apps',cb),
  onSettings:cb=>sub('koi:settings',cb),
  onClose:cb=>ipcRenderer.on('koi:close',()=>cb()),
  onWarm:cb=>ipcRenderer.on('koi:warm',()=>cb()),
  hide:()=>ipcRenderer.send('koi:hide'),
  iconBad:p=>ipcRenderer.send('koi:iconBad',p),
  launch:(p,n)=>ipcRenderer.send('koi:launch',p,n),
  action:(k,p,n)=>ipcRenderer.send('koi:action',k,p,n),
  tourDone:k=>ipcRenderer.send('koi:tourDone',k==='new'?'new':'tour'),
  s:{
    get:()=>ipcRenderer.invoke('koi:s:get'),
    pause:()=>ipcRenderer.invoke('koi:s:pause'),
    resume:()=>ipcRenderer.invoke('koi:s:resume'),
    setMain:a=>ipcRenderer.invoke('koi:s:setMain',a),
    addHotkey:(a,n,p)=>ipcRenderer.invoke('koi:s:add',a,n,p),
    updateHotkey:(i,a)=>ipcRenderer.invoke('koi:s:update',i,a),
    removeHotkey:i=>ipcRenderer.invoke('koi:s:remove',i),
    openAccess:()=>ipcRenderer.send('koi:s:openAccess'),
    fixPerm:()=>ipcRenderer.send('koi:s:fixPerm'),
    sw:(k,v)=>ipcRenderer.invoke('koi:s:sw',k,v),
    onChanged:cb=>ipcRenderer.on('koi:s:changed',()=>cb())
  },
  sw:{
    onShow:cb=>sub('sw:show',cb),
    onSelect:cb=>sub('sw:select',cb),
    onUpdate:cb=>sub('sw:update',cb),
    onThumb:cb=>sub('sw:thumb',cb),
    onHide:cb=>ipcRenderer.on('sw:hide',()=>cb()),
    onWarm:cb=>ipcRenderer.on('sw:warm',()=>cb()),
    hover:i=>ipcRenderer.send('sw:hover',i),
    pick:i=>ipcRenderer.send('sw:pick',i),
    wheel:d=>ipcRenderer.send('sw:wheel',d),
    cols:n=>ipcRenderer.send('sw:cols',n),
    key:k=>ipcRenderer.send('sw:key',k),
    perm:()=>ipcRenderer.send('sw:perm')
  },
  perm:{
    state:()=>ipcRenderer.invoke('perm:action','state'),
    onState:cb=>sub('perm:state',cb),
    onHide:cb=>ipcRenderer.on('perm:hide',()=>cb()),
    action:a=>ipcRenderer.invoke('perm:action',a)
  },
  pop:{
    get:()=>ipcRenderer.invoke('pop:get'),
    onState:cb=>sub('pop:state',cb),
    onShow:cb=>sub('pop:show',cb),
    onHide:cb=>ipcRenderer.on('pop:hide',()=>cb()),
    set:(k,v)=>ipcRenderer.send('pop:set',k,v),
    action:a=>ipcRenderer.send('pop:action',a),
    size:h=>ipcRenderer.send('pop:size',h)
  },
  upd:{
    state:()=>ipcRenderer.invoke('upd:action','state'),
    onState:cb=>sub('upd:state',cb),
    onHide:cb=>ipcRenderer.on('upd:hide',()=>cb()),
    action:a=>ipcRenderer.invoke('upd:action',a)
  }
});
